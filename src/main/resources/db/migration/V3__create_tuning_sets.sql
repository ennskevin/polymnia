CREATE TABLE tuning_sets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    palette_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    intervals JSONB NOT NULL,

    CONSTRAINT fk_tuning_sets_palette
        FOREIGN KEY (palette_id)
        REFERENCES palettes(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_tuning_sets_palette_name
        UNIQUE (palette_id, name)
);