CREATE TABLE composition_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    composition_id BIGINT NOT NULL,
    harmony_id BIGINT NOT NULL,
    position INTEGER NOT NULL,
    beats DOUBLE PRECISION NOT NULL,

    CONSTRAINT fk_composition_items_composition
        FOREIGN KEY (composition_id)
        REFERENCES compositions(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_composition_items_harmony
        FOREIGN KEY (harmony_id)
        REFERENCES harmonies(id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_composition_items_position
        UNIQUE (composition_id, position)
);