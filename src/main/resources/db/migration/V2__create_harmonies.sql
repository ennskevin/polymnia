CREATE TABLE harmonies {
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    palette_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    anchor_frequency DOUBLE PRECISION,
    source_tuning_set_id BIGINT,
    intervals JSONB NOT NULL,

    CONSTRAINT fk_harmonies_palette
        FOREIGN KEY (palette_id)
        REFERENCES palettes(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_harmonies_palette_name
        UNIQUE (palette_id, name)
};